package bot

import (
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	"github.com/tigersoldier/pi-gateway/gwclient"
	"github.com/tigersoldier/pi-gateway/protocol"
)

// turnOutcome is the terminal story of one turn. Pi reports the reasons
// separately — assistant stop reason, retry, compaction, extension and session
// lifecycle — and one turn can produce several. Keeping them in one place lets
// the failure path choose the most useful public message instead of
// special-casing the provider error that happened to be seen first.
type turnOutcome struct {
	stopReason      string
	errorMessage    string
	aborted         bool
	sessionState    string
	sessionReason   string
	sessionExitCode *int
	retryError      string
	retryAttemptErr string
	compactionError string
	extensionError  string
	gatewayError    string
	readError       string
}

type assistantEnd struct {
	stopReason   string
	errorMessage string
}

func assistantEndFromJSON(raw json.RawMessage) (assistantEnd, bool) {
	var message struct {
		Role         string `json:"role"`
		StopReason   string `json:"stopReason"`
		ErrorMessage string `json:"errorMessage"`
	}
	if json.Unmarshal(raw, &message) != nil || message.Role != "assistant" {
		return assistantEnd{}, false
	}
	return assistantEnd{stopReason: message.StopReason, errorMessage: message.ErrorMessage}, true
}

// recordAssistantEnd remembers how the last assistant message ended. Pi's
// get_last_assistant_text is text-only, so a failed assistant message has no
// text to read back; its stopReason and errorMessage are the only explanation
// available to the turn.
func (s *turnState) recordAssistantEnd(ev gwclient.Event) {
	var end struct {
		Message json.RawMessage `json:"message"`
	}
	if ev.Unmarshal(&end) != nil {
		return
	}
	message, ok := assistantEndFromJSON(end.Message)
	if !ok {
		return
	}
	detail := compactTurnError(message.errorMessage)
	s.mu.Lock()
	if !s.started {
		s.mu.Unlock()
		return
	}
	s.outcome.stopReason = message.stopReason
	s.outcome.errorMessage = detail
	s.mu.Unlock()
}

// recordAgentEnd is the fallback for a reconnect or replay that lost the
// message_end frames. agent_end carries the messages generated by one low-level
// run, and the last assistant message in it is that run's outcome.
func (s *turnState) recordAgentEnd(ev gwclient.Event) {
	var end struct {
		Messages []json.RawMessage `json:"messages"`
	}
	if ev.Unmarshal(&end) != nil {
		return
	}
	var last assistantEnd
	found := false
	for i := len(end.Messages) - 1; i >= 0; i-- {
		if message, ok := assistantEndFromJSON(end.Messages[i]); ok {
			last, found = message, true
			break
		}
	}
	if !found {
		return
	}
	detail := compactTurnError(last.errorMessage)
	s.mu.Lock()
	if !s.started {
		s.mu.Unlock()
		return
	}
	s.outcome.stopReason = last.stopReason
	s.outcome.errorMessage = detail
	s.mu.Unlock()
}

func (s *turnState) recordAgentSettled(ev gwclient.Event) {
	var settled struct {
		Aborted bool `json:"aborted"`
	}
	if ev.Unmarshal(&settled) == nil && settled.Aborted {
		s.mu.Lock()
		if s.started {
			s.outcome.aborted = true
		}
		s.mu.Unlock()
	}
}

func (s *turnState) recordAutoRetryStart(ev gwclient.Event) {
	var retry struct {
		ErrorMessage string `json:"errorMessage"`
	}
	if ev.Unmarshal(&retry) != nil {
		return
	}
	if detail := compactTurnError(retry.ErrorMessage); detail != "" {
		s.mu.Lock()
		if s.started {
			s.outcome.retryAttemptErr = detail
		}
		s.mu.Unlock()
	}
}

func (s *turnState) recordAutoRetryEnd(ev gwclient.Event) {
	var retry struct {
		Success    bool   `json:"success"`
		FinalError string `json:"finalError"`
	}
	if ev.Unmarshal(&retry) != nil {
		return
	}
	detail := compactTurnError(retry.FinalError)
	s.mu.Lock()
	if !s.started {
		s.mu.Unlock()
		return
	}
	switch {
	case retry.Success:
		s.outcome.retryError = ""
		s.outcome.retryAttemptErr = ""
	case detail != "":
		s.outcome.retryError = detail
	case s.outcome.retryAttemptErr != "":
		s.outcome.retryError = s.outcome.retryAttemptErr
	}
	s.mu.Unlock()
}

func (s *turnState) recordCompactionEnd(ev gwclient.Event) {
	var end struct {
		ErrorMessage string          `json:"errorMessage"`
		Aborted      bool            `json:"aborted"`
		Result       json.RawMessage `json:"result"`
	}
	if ev.Unmarshal(&end) != nil {
		return
	}
	detail := compactTurnError(end.ErrorMessage)
	failed := len(end.Result) == 0 || strings.TrimSpace(string(end.Result)) == "null"
	s.mu.Lock()
	if !s.started {
		s.mu.Unlock()
		return
	}
	if failed && !end.Aborted && detail != "" {
		s.outcome.compactionError = detail
	} else {
		s.outcome.compactionError = ""
	}
	s.mu.Unlock()
}

func (s *turnState) recordExtensionError(ev gwclient.Event) {
	var extension struct {
		Event string `json:"event"`
		Error string `json:"error"`
	}
	if ev.Unmarshal(&extension) != nil {
		return
	}
	detail := compactTurnError(extension.Error)
	if detail == "" {
		return
	}
	if extension.Event != "" {
		detail = extension.Event + ": " + detail
	}
	s.mu.Lock()
	if s.started {
		s.outcome.extensionError = detail
	}
	s.mu.Unlock()
}

// recordSessionState remembers a process failure that can end the turn. A
// state that arrives after the turn settled is not this turn's outcome: the
// session may crash or be stopped after the answer was already delivered.
func (s *turnState) recordSessionState(ev gwclient.Event) {
	state, err := ev.SessionState()
	if err != nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.eventDone || !s.started {
		return
	}
	switch state.State {
	case "crashed", "stopped", "restarting", protocol.SessionStateDeleted:
		s.outcome.sessionState = state.State
		s.outcome.sessionReason = compactTurnError(state.Reason)
		if state.ExitCode != nil {
			code := *state.ExitCode
			s.outcome.sessionExitCode = &code
		}
	}
}

func (s *turnState) recordGatewayError(ev gwclient.Event) {
	var gateway protocol.ErrorEvent
	if ev.Unmarshal(&gateway) != nil {
		return
	}
	message := compactTurnError(gateway.Message)
	if gateway.Code != "" && !strings.Contains(message, gateway.Code) {
		if message == "" {
			message = gateway.Code
		} else {
			message = gateway.Code + ": " + message
		}
	}
	if message == "" {
		return
	}
	s.mu.Lock()
	if s.started {
		s.outcome.gatewayError = message
	}
	s.mu.Unlock()
}

func (s *turnState) recordReadError(err error) {
	if err == nil {
		return
	}
	detail := compactTurnError(err.Error())
	if detail == "" {
		return
	}
	s.mu.Lock()
	s.outcome.readError = detail
	s.mu.Unlock()
}

// turnFailure is the failure a prompt turn reports, including the generic
// no-answer case when the turn produced no text and no terminal error.
func (s *turnState) turnFailure(hasText bool) error {
	s.mu.Lock()
	outcome := s.outcome
	s.mu.Unlock()
	return outcome.failure(hasText)
}

// terminalFailure reports only an explicit terminal error. Synthetic observed
// turns use it so a successful, textless wake is not posted as a failure.
func (s *turnState) terminalFailure(hasText bool) error {
	s.mu.Lock()
	outcome := s.outcome
	s.mu.Unlock()
	if !outcome.explicitFailure(hasText) {
		return nil
	}
	return outcome.explicitError()
}

func (o turnOutcome) failure(hasText bool) error {
	if o.explicitFailure(hasText) {
		return o.explicitError()
	}
	if !hasText {
		return errors.New("the agent produced no answer")
	}
	return nil
}

func (o turnOutcome) explicitFailure(hasText bool) bool {
	if o.hardSessionFailure() {
		return true
	}
	switch o.stopReason {
	case "error", "length":
		return true
	case "aborted", "deferred":
		return !hasText
	}
	if o.aborted {
		return !hasText
	}
	if o.stopReason == "stop" || o.stopReason == "toolUse" {
		return false
	}
	return o.retryError != "" || o.compactionError != "" || o.extensionError != "" ||
		o.gatewayError != "" || o.readError != ""
}

func (o turnOutcome) explicitError() error {
	if message, cause := o.sessionFailure(); message != "" {
		return publicError(message, cause)
	}
	switch o.stopReason {
	case "error":
		if o.errorMessage != "" {
			return publicError("the model request failed: "+o.errorMessage, nil)
		}
		return publicError("the model request failed", nil)
	case "length":
		return publicError("the model stopped at its output limit; the answer is incomplete", nil)
	case "aborted":
		return publicError("the turn was stopped before it produced an answer", nil)
	case "deferred":
		return publicError("the model deferred the response and no final answer arrived", nil)
	}
	if o.aborted {
		return publicError("the turn was stopped before it produced an answer", nil)
	}
	switch {
	case o.retryError != "":
		return publicError("the model request failed after retries: "+o.retryError, nil)
	case o.compactionError != "":
		return publicError("the conversation could not be compacted: "+o.compactionError, nil)
	case o.extensionError != "":
		return publicError("an extension failed during this turn: "+o.extensionError, nil)
	case o.gatewayError != "":
		return publicError("the gateway reported an error while this turn was running", errors.New(o.gatewayError))
	case o.readError != "":
		return publicError("I couldn't read the agent's answer", errors.New(o.readError))
	}
	return errors.New("the agent produced no answer")
}

func (o turnOutcome) taskFailed(hasText bool) bool {
	if o.hardSessionFailure() {
		return true
	}
	switch o.stopReason {
	case "error", "length", "aborted":
		return true
	case "deferred":
		return !hasText
	}
	if o.aborted {
		return true
	}
	if o.stopReason == "stop" || o.stopReason == "toolUse" {
		return false
	}
	return o.explicitFailure(hasText)
}

func (o turnOutcome) hardSessionFailure() bool {
	switch o.sessionState {
	case "crashed", "stopped", "restarting", protocol.SessionStateDeleted:
		return true
	}
	return false
}

func (o turnOutcome) sessionFailure() (string, error) {
	cause := o.sessionCause()
	switch o.sessionState {
	case "crashed":
		return "the session process crashed while this turn was running", cause
	case "stopped":
		return "the session process was stopped while this turn was running", cause
	case "restarting":
		return "the session restarted while this turn was running", cause
	case protocol.SessionStateDeleted:
		return "this session was deleted outside pi-chat; the next message starts a new one", cause
	}
	return "", nil
}

func (o turnOutcome) sessionCause() error {
	var parts []string
	if o.sessionReason != "" {
		parts = append(parts, "reason "+o.sessionReason)
	}
	if o.sessionExitCode != nil {
		parts = append(parts, fmt.Sprintf("exit code %d", *o.sessionExitCode))
	}
	if len(parts) == 0 {
		return nil
	}
	return errors.New(strings.Join(parts, ", "))
}

// turnSetupError gives a session-attach failure a public explanation while
// keeping the gateway's own error available to the log.
func turnSetupError(err error) error {
	if errors.Is(err, errSessionGone) {
		return publicError("this session was deleted outside pi-chat; the next message starts a new one", err)
	}
	return publicError("I couldn't connect to the agent's session", err)
}

// compactTurnError keeps a provider's explanation to one line and a bounded
// length; it is shown in Slack, not logged, so ANSI and whitespace are noise.
func compactTurnError(text string) string {
	text = strings.Join(strings.Fields(stripANSI(text)), " ")
	if runes := []rune(text); len(runes) > maxTurnErrorRunes {
		return string(runes[:maxTurnErrorRunes-1]) + "…"
	}
	return text
}
